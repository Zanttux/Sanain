//! The list of open files, restored on the next launch.
//!
//! Format (UTF-8 text): first line `sanain-session 1`, then `active=N` and
//! one line per tab in order: `path=...` for a file, `untitled=ID` for an
//! untitled tab kept by hot exit (its text is recovery snapshot `ID`).
//! A tab line may be followed by `recovery=ID` (a file tab's unsaved edits
//! kept by hot exit) and `caret=A,H` (the selection's anchor and head, in
//! characters). Then `pinned=I` for each pinned tab (an index into the
//! tabs). Unknown lines are ignored. Paths that are not valid UTF-8 or
//! contain line breaks are not recorded.
//!
//! Versions before hot exit ignore `untitled`, `recovery` and `caret`
//! lines; with untitled tabs in the file, their tab indices (active,
//! pinned, panes) then point at neighbouring tabs. Nothing is lost: the
//! untitled text is in the recovery folder, which every version restores.
//!
//! A split editor adds its layout after those lines:
//!
//! ```text
//! split=right            groups side by side (or `down`: stacked)
//! group=0.4              a group and its share of the area
//! pane=0,1               a pane in that group: path index, share
//! group=0.6
//! pane=1,0.5
//! pane=2,0.5
//! focus=2                the focused pane, in reading order
//! ```
//!
//! Older versions ignore these lines (and so open the files unsplit). A
//! layout that does not parse is dropped; the rest of the session still
//! loads.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use crate::panes::{Direction, GroupLayout, Layout};

const HEADER: &str = "sanain-session 1";

/// One tab of a session.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct SessionTab {
    /// The file; `None` for an untitled tab kept by hot exit.
    pub path: Option<PathBuf>,
    /// Hot exit: the recovery snapshot holding the tab's unsaved text.
    pub recovery: Option<String>,
    /// Primary selection as (anchor, head) char indices.
    pub caret: Option<(usize, usize)>,
}

impl SessionTab {
    pub fn file(path: impl Into<PathBuf>) -> Self {
        Self {
            path: Some(path.into()),
            ..Self::default()
        }
    }
}

#[derive(Debug, Clone, Default, PartialEq)]
pub struct Session {
    pub tabs: Vec<SessionTab>,
    /// Index into `tabs` of the active tab.
    pub active: usize,
    /// Indices into `tabs` of pinned tabs.
    pub pinned: Vec<usize>,
    /// The split editor's layout; each pane shows an index into `tabs`.
    pub layout: Option<Layout<usize>>,
}

/// Recovery ids are generated by [`text3_io::recovery::RecoveryStore::new_id`];
/// anything else in a session file is ignored.
fn valid_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 64
        && id
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
}

/// Reads the split lines as they come; any error spoils the whole layout.
#[derive(Default)]
struct LayoutParser {
    layout: Option<Layout<usize>>,
    bad: bool,
}

impl LayoutParser {
    fn line(&mut self, key: &str, v: &str) {
        if self.bad {
            return;
        }
        let ok = match (key, &mut self.layout) {
            ("split", None) => {
                let dir = match v {
                    "right" => Some(Direction::Right),
                    "down" => Some(Direction::Down),
                    _ => None,
                };
                self.layout = dir.map(|dir| Layout {
                    dir,
                    groups: Vec::new(),
                    focus: 0,
                });
                dir.is_some()
            }
            ("group", Some(l)) => v.parse().ok().is_some_and(|share| {
                l.groups.push(GroupLayout {
                    share,
                    panes: Vec::new(),
                });
                true
            }),
            ("pane", Some(l)) => {
                let parsed = v
                    .split_once(',')
                    .and_then(|(i, f)| Some((i.parse().ok()?, f.parse().ok()?)));
                match (parsed, l.groups.last_mut()) {
                    (Some(p), Some(g)) => {
                        g.panes.push(p);
                        true
                    }
                    _ => false,
                }
            }
            ("focus", Some(l)) => v.parse().ok().is_some_and(|f| {
                l.focus = f;
                true
            }),
            _ => false,
        };
        self.bad = !ok;
    }

    fn finish(self, tabs: usize) -> Option<Layout<usize>> {
        let l = self.layout.filter(|_| !self.bad)?;
        let valid = l.len() >= 2
            && l.focus < l.len()
            && l.groups
                .iter()
                .all(|g| !g.panes.is_empty() && g.panes.iter().all(|(i, _)| *i < tabs));
        valid.then_some(l)
    }
}

impl Session {
    /// A session of files only.
    pub fn of_paths(paths: impl IntoIterator<Item = PathBuf>) -> Self {
        Self {
            tabs: paths.into_iter().map(SessionTab::file).collect(),
            ..Self::default()
        }
    }

    /// The files in the session, in tab order.
    pub fn paths(&self) -> Vec<PathBuf> {
        self.tabs.iter().filter_map(|t| t.path.clone()).collect()
    }

    pub fn encode(&self) -> String {
        let mut out = format!("{HEADER}\nactive={}\n", self.active);
        let mut written = 0;
        let mut pinned = Vec::new();
        // Index each recorded tab gets in the file.
        let mut index = vec![None; self.tabs.len()];
        for (i, t) in self.tabs.iter().enumerate() {
            let recovery = t.recovery.as_deref().filter(|id| valid_id(id));
            let line = match (&t.path, recovery) {
                (Some(p), _) => p
                    .to_str()
                    .filter(|s| !s.contains(['\n', '\r']))
                    .map(|s| format!("path={s}\n")),
                (None, Some(id)) => Some(format!("untitled={id}\n")),
                (None, None) => None,
            };
            let Some(line) = line else { continue };
            if self.pinned.contains(&i) {
                pinned.push(written);
            }
            index[i] = Some(written);
            written += 1;
            out.push_str(&line);
            if let (Some(_), Some(id)) = (&t.path, recovery) {
                out.push_str(&format!("recovery={id}\n"));
            }
            if let Some((a, h)) = t.caret {
                out.push_str(&format!("caret={a},{h}\n"));
            }
        }
        for i in pinned {
            out.push_str(&format!("pinned={i}\n"));
        }
        let layout = self
            .layout
            .clone()
            .map(|l| l.filter_map(|i| index.get(i).copied().flatten()))
            .filter(|l| l.len() >= 2);
        if let Some(l) = layout {
            let dir = match l.dir {
                Direction::Right => "right",
                Direction::Down => "down",
            };
            out.push_str(&format!("split={dir}\n"));
            for g in &l.groups {
                out.push_str(&format!("group={}\n", g.share));
                for (i, share) in &g.panes {
                    out.push_str(&format!("pane={i},{share}\n"));
                }
            }
            out.push_str(&format!("focus={}\n", l.focus));
        }
        out
    }

    /// Parse a session file. Anything malformed yields `None`, never a panic.
    pub fn decode(text: &str) -> Option<Self> {
        let mut lines = text.lines();
        if lines.next()? != HEADER {
            return None;
        }
        let mut s = Session::default();
        let mut layout = LayoutParser::default();
        for line in lines {
            match line.split_once('=') {
                Some(("active", v)) => s.active = v.parse().ok()?,
                Some(("path", v)) if !v.is_empty() => s.tabs.push(SessionTab::file(v)),
                // An invalid id still takes its place, so indices stay
                // right; the tab is skipped on restore.
                Some(("untitled", v)) => s.tabs.push(SessionTab {
                    recovery: valid_id(v).then(|| v.to_owned()),
                    ..SessionTab::default()
                }),
                Some(("recovery", v)) => {
                    if let Some(t) = s.tabs.last_mut().filter(|t| t.path.is_some()) {
                        t.recovery = valid_id(v).then(|| v.to_owned());
                    }
                }
                Some(("caret", v)) => {
                    let caret = v
                        .split_once(',')
                        .and_then(|(a, h)| Some((a.parse().ok()?, h.parse().ok()?)));
                    if let Some(t) = s.tabs.last_mut() {
                        t.caret = caret;
                    }
                }
                Some(("pinned", v)) => s.pinned.extend(v.parse::<usize>().ok()),
                Some((k @ ("split" | "group" | "pane" | "focus"), v)) => layout.line(k, v),
                _ => {}
            }
        }
        s.layout = layout.finish(s.tabs.len());
        if s.active >= s.tabs.len() {
            s.active = 0;
        }
        let n = s.tabs.len();
        s.pinned.retain(|i| *i < n);
        Some(s)
    }

    pub fn load(file: &Path) -> Option<Self> {
        Self::decode(&fs::read_to_string(file).ok()?)
    }

    pub fn save(&self, file: &Path) -> io::Result<()> {
        if let Some(dir) = file.parent() {
            fs::create_dir_all(dir)?;
        }
        text3_io::write_atomic(file, self.encode().as_bytes(), None).map(|_| ())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trip_and_clamping() {
        let s = Session {
            active: 1,
            pinned: vec![1],
            ..Session::of_paths(["/a/b.txt".into(), "/c d/ä.md".into()])
        };
        assert_eq!(Session::decode(&s.encode()), Some(s));
        let bad_active = "sanain-session 1\nactive=9\npath=/x\n";
        assert_eq!(Session::decode(bad_active).unwrap().active, 0);
    }

    #[test]
    fn rejects_garbage_without_panicking() {
        for text in [
            "",
            "nope",
            "sanain-session 2\n",
            "sanain-session 1\nactive=x\n",
        ] {
            assert_eq!(Session::decode(text), None, "{text:?}");
        }
        let ok = Session::decode("sanain-session 1\nfuture=1\npath=/x\n").unwrap();
        assert_eq!(ok.paths(), vec![PathBuf::from("/x")]);
    }

    #[test]
    fn save_and_load_file() {
        let dir = tempfile::tempdir().unwrap();
        let f = dir.path().join("sub/session");
        let s = Session::of_paths([dir.path().join("x.txt")]);
        s.save(&f).unwrap();
        assert_eq!(Session::load(&f), Some(s));
    }

    fn three_pane_layout() -> Layout<usize> {
        Layout {
            dir: Direction::Right,
            groups: vec![
                GroupLayout {
                    share: 0.25,
                    panes: vec![(0, 1.0)],
                },
                GroupLayout {
                    share: 0.75,
                    panes: vec![(1, 0.3), (2, 0.7)],
                },
            ],
            focus: 2,
        }
    }

    fn three_paths() -> Session {
        Session::of_paths(["/a".into(), "/b".into(), "/c".into()])
    }

    #[test]
    fn split_layout_round_trips() {
        let s = Session {
            active: 2,
            pinned: vec![0],
            layout: Some(three_pane_layout()),
            ..three_paths()
        };
        let text = s.encode();
        assert!(
            text.contains("split=right\ngroup=0.25\npane=0,1\n"),
            "{text}"
        );
        assert_eq!(Session::decode(&text), Some(s));
    }

    #[test]
    fn old_session_files_load_unsplit() {
        let s =
            Session::decode("sanain-session 1\nactive=1\npath=/a\npath=/b\npinned=0\n").unwrap();
        assert_eq!(s.tabs.len(), 2);
        assert_eq!(s.active, 1);
        assert_eq!(s.layout, None);
    }

    #[test]
    fn malformed_split_is_ignored_and_the_rest_loads() {
        let base = "sanain-session 1\nactive=0\npath=/a\npath=/b\n";
        for split in [
            "split=sideways\ngroup=1\npane=0,1\npane=1,1\nfocus=0\n",
            "group=1\npane=0,1\n",
            "split=right\npane=0,1\ngroup=1\npane=1,1\n",
            "split=right\ngroup=x\npane=0,1\ngroup=1\npane=1,1\n",
            "split=right\ngroup=1\npane=0\ngroup=1\npane=1,1\n",
            "split=right\ngroup=1\npane=0,1\ngroup=1\npane=7,1\n",
            "split=right\ngroup=1\npane=0,1\ngroup=1\npane=1,1\nfocus=-1\n",
            "split=right\ngroup=1\npane=0,1\ngroup=1\npane=1,1\nfocus=5\n",
            "split=right\ngroup=1\npane=0,1\ngroup=1\n",
            "split=right\ngroup=1\npane=0,1\n",
            "split=right\nsplit=down\ngroup=1\npane=0,1\ngroup=1\npane=1,1\n",
        ] {
            let s = Session::decode(&format!("{base}{split}")).unwrap();
            assert_eq!(s.layout, None, "{split:?}");
            assert_eq!(s.tabs.len(), 2);
        }
    }

    #[test]
    fn layout_follows_paths_that_are_not_recorded() {
        let s = Session {
            layout: Some(three_pane_layout()),
            ..Session::of_paths(["/a".into(), "/bad\npath".into(), "/c".into()])
        };
        let back = Session::decode(&s.encode()).unwrap();
        assert_eq!(back.paths(), vec![PathBuf::from("/a"), PathBuf::from("/c")]);
        let l = back.layout.unwrap();
        assert_eq!(l.len(), 2);
        assert_eq!(l.groups[1].panes[0].0, 1);
        assert_eq!(l.focus, 1);
    }

    #[test]
    fn hot_exit_tabs_round_trip() {
        let s = Session {
            tabs: vec![
                SessionTab {
                    caret: Some((3, 7)),
                    ..SessionTab::file("/a.txt")
                },
                SessionTab {
                    recovery: Some("18f-2a-0".into()),
                    caret: Some((0, 0)),
                    ..SessionTab::default()
                },
                SessionTab {
                    recovery: Some("18f-2a-1".into()),
                    ..SessionTab::file("/b.txt")
                },
            ],
            active: 1,
            pinned: vec![1],
            layout: Some(three_pane_layout()),
        };
        let text = s.encode();
        assert!(
            text.contains("path=/a.txt\ncaret=3,7\nuntitled=18f-2a-0\ncaret=0,0\npath=/b.txt\nrecovery=18f-2a-1\n"),
            "{text}"
        );
        assert_eq!(Session::decode(&text), Some(s));
    }

    #[test]
    fn untitled_tab_without_snapshot_is_not_recorded() {
        let s = Session {
            tabs: vec![SessionTab::default(), SessionTab::file("/a")],
            active: 1,
            ..Session::default()
        };
        let back = Session::decode(&s.encode()).unwrap();
        assert_eq!(back.tabs, vec![SessionTab::file("/a")]);
        assert_eq!(back.active, 0, "index follows the recorded tabs");
    }

    #[test]
    fn hostile_recovery_ids_are_ignored_but_keep_their_place() {
        let text = "sanain-session 1\nactive=1\nuntitled=../../etc/passwd\npath=/a\nrecovery=a/b\ncaret=x\n";
        let s = Session::decode(text).unwrap();
        assert_eq!(s.tabs.len(), 2);
        assert_eq!(s.tabs[0].recovery, None);
        assert_eq!(s.tabs[1].recovery, None);
        assert_eq!(s.tabs[1].caret, None);
        assert_eq!(s.active, 1);
        // Written back, the unusable untitled entry disappears.
        assert!(!s.encode().contains("untitled"));
    }
}
