#!/usr/bin/env python3
"""Write the third-party notices file shipped with binary releases.

Collects every crate linked into Text³ (normal dependencies of the
workspace members, all platforms), with its license expression,
repository and the license/notice texts found in the crate package.
Uses only `cargo metadata` and the local registry sources; needs no
network access after `cargo fetch`.

Usage: scripts/third-party-notices.py [OUTPUT]   (default: THIRD_PARTY_NOTICES.md)
Exit status 1 if any crate ships no license text (listed on stderr), so
the release checklist catches it.
"""

import json
import os
import subprocess
import sys

TEXT_PREFIXES = ("license", "licence", "copying", "notice", "unlicense")

MIT_TEXT = """Permission is hereby granted, free of charge, to any person obtaining a
copy of this software and associated documentation files (the "Software"),
to deal in the Software without restriction, including without limitation
the rights to use, copy, modify, merge, publish, distribute, sublicense,
and/or sell copies of the Software, and to permit persons to whom the
Software is furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in
all copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING
FROM, OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER
DEALINGS IN THE SOFTWARE."""


# Full license texts appended once, taken from packages that ship them, for
# crates that name the license but do not include its file.
APPENDIX = {
    "Apache-2.0": ("Apache License", "Version 2.0"),
    "BSL-1.0": ("Boost Software License - Version 1.0",),
}


def text_files(root):
    return sorted(
        f
        for f in os.listdir(root)
        if f.lower().startswith(TEXT_PREFIXES) and os.path.isfile(os.path.join(root, f))
    )


def spdx_ids(expr):
    return set(
        expr.replace("(", " ").replace(")", " ").replace("/", " OR ").split()
    ) - {"OR", "AND", "WITH"}


def main() -> int:
    out_path = sys.argv[1] if len(sys.argv) > 1 else "THIRD_PARTY_NOTICES.md"
    meta = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--locked"],
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    )
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    members = set(meta["workspace_members"])

    # Walk normal (non-dev, non-build) dependencies from the workspace.
    seen, stack = set(), list(members)
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])

    crates = sorted(
        (packages[p] for p in seen - members),
        key=lambda p: (p["name"], p["version"]),
    )
    missing = []
    appendix = {}
    for p in crates:
        root = os.path.dirname(p["manifest_path"])
        for t in text_files(root):
            with open(os.path.join(root, t), encoding="utf-8", errors="replace") as f:
                body = f.read()
            for spdx, marks in APPENDIX.items():
                if spdx not in appendix and all(m in body for m in marks):
                    appendix[spdx] = body.strip()
    lines = [
        "# Third-party notices",
        "",
        "Text³ is licensed under the Mozilla Public License 2.0. It includes",
        f"the following {len(crates)} third-party components, each under its own",
        "license as stated below. Generated by scripts/third-party-notices.py.",
        "",
    ]
    for p in crates:
        root = os.path.dirname(p["manifest_path"])
        texts = text_files(root)
        lines.append(f"## {p['name']} {p['version']}")
        lines.append("")
        lines.append(f"- License: {p.get('license') or 'see license file'}")
        if p.get("repository"):
            lines.append(f"- Source: {p['repository']}")
        if p.get("authors"):
            lines.append(f"- Authors: {', '.join(p['authors'])}")
        lines.append("")
        if not texts:
            ids = spdx_ids(p.get("license") or "")
            authors = ", ".join(p.get("authors") or []) or f"the {p['name']} authors"
            if "MIT" in ids:
                # The package omits the file; MIT's notice is the standard
                # text with the crate's authors as copyright holders.
                lines.append("<details><summary>MIT License</summary>")
                lines.append("")
                lines.append("```text")
                lines.append(f"Copyright (c) {authors}")
                lines.append("")
                lines.append(MIT_TEXT)
                lines.append("```")
                lines.append("")
                lines.append("</details>")
                lines.append("")
            elif any(i in appendix for i in ids):
                names = ", ".join(sorted(i for i in ids if i in appendix))
                lines.append(f"_{names}: full text at the end of this file._")
                lines.append("")
            else:
                missing.append(f"{p['name']} {p['version']}")
                lines.append("_No license file in the crate package; the license above applies._")
                lines.append("")
        for t in texts:
            with open(os.path.join(root, t), encoding="utf-8", errors="replace") as f:
                body = f.read().strip()
            lines.append(f"<details><summary>{t}</summary>")
            lines.append("")
            lines.append("```text")
            lines.append(body.replace("```", "'''"))
            lines.append("```")
            lines.append("")
            lines.append("</details>")
            lines.append("")
    for spdx, body in sorted(appendix.items()):
        lines += [f"## License text: {spdx}", "", "```text", body, "```", ""]
    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"{out_path}: {len(crates)} crates, {len(missing)} without a license file")
    if missing:
        print("Crates without license text (supply it before release):", file=sys.stderr)
        for m in missing:
            print(f"  {m}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
